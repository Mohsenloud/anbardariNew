#!/bin/bash
# ==============================================================================
# اسکریپت به‌روزرسانی خودکار سامانه روی سرور لینوکس (VPS)
# با اجرای این اسکریپت، آخرین نسخه از گیت‌هاب دریافت شده و کانتینر بدون قطعی بازسازی می‌شود.
# ==============================================================================

set -e

echo "---------------------------------------------------------"
echo "🚀 شروع فرایند به‌روزرسانی سامانه..."
echo "---------------------------------------------------------"

# ۰. تهیه نسخه پشتیبان خودکار از دیتابیس قبل از هرگونه تغییر
if [ -f "./data/database.json" ]; then
  mkdir -p ./data/backups
  BACKUP_FILE="./data/backups/database-backup-$(date +%Y%m%d_%H%M%S).json"
  cp ./data/database.json "$BACKUP_FILE"
  echo "🛡️ از اطلاعات فعلی سرور بکاپ ایمن تهیه شد: $BACKUP_FILE"
fi

# ۱. دریافت آخرین تغییرات سورس کد از گیت‌هاب
echo "📥 دریافت آخرین تغییرات از گیت‌هاب..."
git fetch --all
git reset --hard origin/main

# ۲. بیلد و اجرای مجدد کانتینر داکر
echo "🐳 ساخت ایمیج جدید و راه‌اندازی کانتینر..."
docker compose build --pull
docker compose up -d --remove-orphans

# ۳. پاک‌سازی لایه‌ها و ایمیج‌های قدیمی برای آزاد ماندن فضای دیسک
echo "🧹 پاک‌سازی ایمیج‌های موقت و قدیمی..."
docker image prune -f

echo "---------------------------------------------------------"
echo "✅ به‌روزرسانی با موفقیت کامل شد!"
echo "برنامه اکنون روی پورت 3000 در حال اجرا است."
echo "---------------------------------------------------------"
