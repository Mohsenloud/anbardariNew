#!/usr/bin/env bash
set -e

echo "====================================================="
echo "🚀 شروع فرآیند بروزرسانی سریع سامانه فاکتور و انبارداری..."
echo "====================================================="

# ۱. اطمینان از وجود پوشه دیتابیس و بکاپ روی هاست
mkdir -p ./data/backups

# ۲. ایجاد یک کپی پشتیبان ایمن روی هاست قبل از هرگونه عملیات آپدیت
if [ -f "./data/database.json" ]; then
  TIMESTAMP=$(date +"%Y%m%d_%H%M%S")
  cp ./data/database.json "./data/backups/pre_deploy_${TIMESTAMP}.json"
  echo "✅ کپی پشتیبان اضطراری قبل از آپدیت ساخته شد: pre_deploy_${TIMESTAMP}.json"
fi

# ۳. دریافت آخرین تغییرات کد از گیت‌هاب
if [ -d ".git" ]; then
  echo "📥 دریافت آخرین تغییرات از مخزن Git..."
  git pull origin main
fi

# ۴. بیلد سریع با استفاده از کش لایه‌های داکر و جایگزینی آنی کانتینر بدون خاموش کردن دیتابیس
echo "⚡ در حال ساخت نسخه جدید و بروزرسانی آنی کانتینرها..."
docker compose up -d --build

# ۵. بارگذاری مجدد تنظیمات Nginx بدون قطعی
docker exec mana_nginx_proxy nginx -s reload 2>/dev/null || true

echo "====================================================="
echo "✅ بروزرسانی با موفقیت و در کمترین زمان انجام شد!"
echo "🌐 برنامه روی پورت 3000 در دسترس است."
echo "====================================================="
